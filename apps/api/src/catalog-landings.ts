export const catalogLanding = (path: string) => catalogLandings.find(page => page.path === path);
const norm = (value: unknown) => String(value ?? '').normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
interface Watch { name: string; brand: string | null; gender: string | null; category: string | null; attributes: Record<string, unknown> }
export function watchSeries(product: Watch): string[] {
  const brand = norm(product.brand);
  const declared = Object.entries(product.attributes).filter(([key]) => /^(serija|series|kolekcija|collection)$/.test(norm(key))).flatMap(([,value]) => Array.isArray(value) ? value.map(String) : [String(value)]);
  const text = norm([product.name,product.category,...declared].join(' '));
  const model = product.name.toUpperCase().replace(/\s+/g,'');
  const result = new Set<string>();
  const has = (term: string) => (` ${text} `).includes(` ${norm(term)} `);
  if (brand === 'orient') {
    if (has('Bambino') || /(?:RA-AC0M(?:0[1-4]|09|10|11)|RA-AC0P0[1-4]|RA-AC00\d{2}|RA-AK080[1-8]|FAC0000(?:8W|9W|DD))/.test(model)) result.add('Bambino');
    if (has('Kamasu') || /RA-AA000[1-6]/.test(model)) result.add('Kamasu');
    if (has('Mako') || /(?:RA-AC0Q\d{2}|RA-AA08\d{2})/.test(model)) result.add('Mako');
    if (has('Sun and Moon') || has('Sun & Moon') || /(?:RA-AK00(?:07|08|09|10)|RA-AK080[1-8])/.test(model)) result.add('Sun and Moon');
  }
  if (brand === 'casio') {
    for (const label of ['G-Shock','Edifice','Vintage','Duro']) if (has(label)) result.add(label);
    if (/\bMTP-/.test(product.name.toUpperCase())) result.add('MTP');
    if (/\bMDV-(?:106|107)\b/.test(product.name.toUpperCase())) result.add('Duro');
  }
  return [...result];
}
export function matchesLanding(product: Watch, page: Landing): boolean {
  if (page.brand && norm(product.brand) !== norm(page.brand)) return false;
  if (page.gender && !['unisex',norm(page.gender)].includes(norm(product.gender))) return false;
  if (page.series && !watchSeries(product).includes(page.series)) return false;
  const attributes = Object.entries(product.attributes);
  if (page.movement && !attributes.some(([key,value]) => /^(tip mehanizma|mehanizam|movement|movement type)$/.test(norm(key)) && /\b(automatic|automatski|automatik|automat)\b/.test(norm(value)))) return false;
  if (page.display && !attributes.some(([key,value]) => /^(prikaz|displej|display|tip prikaza|tip sata|display type)$/.test(norm(key)) && /\b(digital|digitalni|digitalan)\b/.test(norm(value)))) return false;
  return true;
}
// A response-only derived facet: no catalog records or staff filter settings are overwritten.
export function withWatchSeries<T extends Watch>(products: T[], filters: Node[]): { products: T[]; filters: Node[] } {
  const enriched = products.map(product => ({...product,attributes:{...product.attributes,seo_watch_series:watchSeries(product)}}));
  const labels = [...new Set(enriched.flatMap(product => product.attributes.seo_watch_series))].sort();
  if (!labels.length) return {products: enriched,filters};
  const series: Node = {id:'watch_series',title:'Serije satova',visible:true,priority:3.5,mode:'options',style:'checkbox',match:'any',unit:'',sources:['spec:seo_watch_series'],children:[],autoAddOptions:false,urlSlug:'serija-sata',
    options:labels.map(label=>({id:`watch_series_${norm(label).replace(/ /g,'_')}`,label,visible:true,color:'',image:'',conditions:[{source:'spec:seo_watch_series',values:[label]}]}))};
  return {products:enriched,filters:[...filters,series]};
}
